inline bool TreeCertified(const definition_tree::Snapshot& tree) {
    if(!tree.Ready() || !tree.ImageBase() || tree.Nodes().empty())return false;
    const auto base=tree.ImageBase(),common=base+0x3BCDD80;
    for(const auto& allocator:tree.Allocators())if(allocator.allocator!=common || (allocator.raw&~uint64_t(7))!=common)return false;
    for(const auto& node:tree.Nodes()){
        if(node.vtable<base || node.work<base || node.destructor<base)return false;
        const auto match=std::find_if(std::begin(CertificateNodes),std::end(CertificateNodes),[&](const CertifiedNode& row){
            return node.vtable==base+row.vtable && node.work==base+row.work && node.destructor==base+row.destructor;
        });
        if(match==std::end(CertificateNodes))return false;
    }
    for(const auto& array:tree.Arrays())if(array.allocator!=base+0x30947E8 || array.freeCallback!=base+0x120F6F0)return false;
    for(const auto& string:tree.Strings())if(string.mode!=1 || !string.capacity || string.allocatorValue ||
        string.fallbackGlobalAddress!=base+definition_tree::StringAllocatorRva || string.fallbackAllocator!=common ||
        (string.fallbackRaw&~uint64_t(7))!=common || string.fallbackFreeAdapter!=base+definition_tree::StringFreeAdapterRva)return false;
    return true;
}
inline bool AllocatorsMatch(const definition_tree::Snapshot& tree,definition_tree::ReadMemory read) {
    if(!TreeCertified(tree) || !read)return false;
    for(const auto& allocator:tree.Allocators()){uint64_t raw{},again{};
        if(!read(allocator.address,&raw,8) || !read(allocator.address,&again,8) || raw!=allocator.raw || again!=raw)return false;
    }
    for(const auto& string:tree.Strings()){uint64_t raw{},again{};
        if(!read(string.fallbackGlobalAddress,&raw,8) || !read(string.fallbackGlobalAddress,&again,8) ||
            raw!=string.fallbackRaw || again!=raw)return false;
    }
    for(const auto& array:tree.Arrays()){uint64_t callback{},again{};
        if(!read(array.allocator+0x20,&callback,8) || !read(array.allocator+0x20,&again,8) ||
            callback!=array.freeCallback || again!=callback)return false;
    }
    return true;
}
