"""Normalize a VS/PS interface for the order-sensitive ViewID pipeline validator.

Unused VS outputs (notably clip distance) must precede rasterizer-generated PS
inputs. Preserve original input semantics/locations and remap load IDs together
with the metadata; never hide ViewID dependencies or disable clipping.
"""
import re
from batch_shaders import metadata

ELEMENT = re.compile(r'i32 (\d+), (!"[^"]+"), i8 (\d+), i8 (\d+), (!\d+), i8 (\d+), '
                     r'i32 (\d+), i8 (\d+), i32 (-?\d+), i8 (\d+), (!\d+|null)')
INPUT_OP = re.compile(r'(@dx\.op\.(?:loadInput|evalSnapped|evalSampleIndex|evalCentroid|attributeAtVertex)\.\w+\(i32 \d+, i32 )(\d+)')


def element_text(fields):
    return (f'i32 {fields[0]}, {fields[1]}, i8 {fields[2]}, i8 {fields[3]}, {fields[4]}, i8 {fields[5]}, '
            f'i32 {fields[6]}, i8 {fields[7]}, i32 {fields[8]}, i8 {fields[9]}, {fields[10]}')


def signature(source, stage, output=False):
    md = metadata(source)
    if md.get(md.get('!dx.shaderModel')) != f'!"{stage}", i32 6, i32 1':
        raise ValueError('Expected converted SM6.1 stage')
    entry = md.get(md.get('!dx.entryPoints'), '')
    match = re.fullmatch(r'void \(\)\* @[\w.]+, !"[^"]*", (!\d+), (?:!\d+|null), (?:!\d+|null)', entry)
    if not match:
        raise ValueError('Unsupported entry metadata')
    signatures = md[match[1]].split(', ')
    ref = signatures[1 if output else 0]
    elements = []
    if ref != 'null':
        for node in md[ref].split(', '):
            value = ELEMENT.fullmatch(md[node])
            if not value:
                raise ValueError('Unsupported interface element: ' + md[node])
            fields = list(value.groups())
            indices = md[fields[4]]
            elements.append(dict(node=node, fields=fields, indices=indices,
                                 key=(fields[1].lower(), fields[3], indices)))
    if len({e['key'] for e in elements}) != len(elements):
        raise ValueError('Duplicate interface semantic')
    return md, ref, elements


def link_pixel_inputs(vertex, pixel):
    _, _, outputs = signature(vertex, 'vs', True)
    md, ref, inputs = signature(pixel, 'ps')
    if ref == 'null':
        # No PS inputs: the runtime can expand the complete preceding signature.
        return pixel, dict(changed=False, added=[], remapped={})
    available = {e['key']: e for e in inputs}
    ordered = []
    added = []
    for out in outputs:
        match = available.pop(out['key'], None)
        if match:
            # Type, shape and packed location remain identical. Interpolation
            # comes from the existing pixel shader, not the producer.
            if any(match['fields'][i] != out['fields'][i] for i in (2, 6, 7, 8, 9)):
                raise ValueError('Interface shape/location needs explicit repacking')
            ordered.append(match)
        else:
            if int(out['fields'][8]) < 0:
                raise ValueError('Unallocated VS output')
            entry = dict(out, node=None, fields=out['fields'].copy())
            entry['fields'][10] = 'null'  # Newly declared PS input is unused.
            ordered.append(entry)
            added.append(out['key'][0])
    for e in inputs:
        if e['key'] in available:
            # These are generated by the rasterizer, never borrowed from a
            # mismatched upstream user semantic. Other additions need proof.
            if int(e['fields'][3]) not in (10, 12, 13, 14, 15):
                raise ValueError('Pixel input absent from vertex output')
            ordered.append(dict(e, fields=e['fields'].copy(), generated=True))
    remap = {int(e['fields'][0]): i for i, e in enumerate(ordered) if e['node']}
    if not added and all(old == new for old, new in remap.items()):
        return pixel, dict(changed=False, added=[], remapped={})
    occupied = set()
    relocated = []
    for e in ordered:
        f = e['fields']
        slots = {(row, col) for row in range(int(f[8]), int(f[8]) + int(f[6]))
                 for col in range(int(f[9]), int(f[9]) + int(f[7])) if row >= 0}
        if slots & occupied and e.get('generated'):
            if int(f[6]) != 1 or int(f[7]) != 1:
                raise ValueError('Only scalar rasterizer-generated inputs may be relocated')
            # Use a completely free register so interpolation/type packing does
            # not acquire a new dependency on neighboring user varyings.
            row = next((r for r in range(32) if not any((r, c) in occupied for c in range(4))), None)
            if row is None:
                raise ValueError('No free register for rasterizer-generated input')
            relocated.append(dict(semantic=e['key'][0], old=[int(f[8]), int(f[9])], new=[row, 0]))
            f[8], f[9] = str(row), '0'
        for row in range(int(f[8]), int(f[8]) + int(f[6])):
            for col in range(int(f[9]), int(f[9]) + int(f[7])):
                if row < 0:
                    continue
                if row >= 32 or col >= 4 or (row, col) in occupied:
                    raise ValueError('New pixel interface overlaps or exceeds register space')
                occupied.add((row, col))
    original_body = '\n'.join(line for line in pixel.splitlines() if not line.startswith('!'))
    def remap_call(m):
        if int(m[2]) not in remap:
            raise ValueError('Input instruction does not identify an original semantic')
        return m[1] + str(remap[int(m[2])])
    result = INPUT_OP.sub(remap_call, pixel)
    next_id = max(map(int, re.findall(r'(?m)^!(\d+) =', pixel))) + 1
    refs = []
    for i, e in enumerate(ordered):
        fields = e['fields'].copy()
        fields[0] = str(i)
        if e['node']:
            node = e['node']
        else:
            index_ref, node = f'!{next_id}', f'!{next_id + 1}'
            next_id += 2
            result += f'\n{index_ref} = !{{{e["indices"]}}}\n'
            fields[4] = index_ref
        text = element_text(fields)
        replacement = f'{node} = !{{{text}}}'
        if e['node']:
            result = result.replace(f'{node} = !{{{md[node]}}}', replacement)
        else:
            result += replacement + '\n'
        refs.append(node)
    result = result.replace(f'{ref} = !{{{md[ref]}}}', ref + ' = !{' + ', '.join(refs) + '}')
    result = re.sub(r'(?m)^!dx.viewIdState = .*\n', '', result)
    inverse = {new: old for old, new in remap.items()}
    body = '\n'.join(line for line in result.splitlines() if not line.startswith('!'))
    body = INPUT_OP.sub(lambda m: m[1] + str(inverse[int(m[2])]), body)
    if body.rstrip() != original_body.rstrip():
        raise ValueError('Non-interface shader instructions changed')
    return result, dict(changed=True, added=added, remapped=remap, relocated=relocated)


if __name__ == '__main__':
    import argparse
    import json
    from pathlib import Path
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('vertex', type=Path)
    p.add_argument('pixel', type=Path)
    p.add_argument('output', type=Path)
    a = p.parse_args()
    result, report = link_pixel_inputs(a.vertex.read_text(), a.pixel.read_text())
    a.output.write_text(result)
    a.output.with_suffix('.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))
