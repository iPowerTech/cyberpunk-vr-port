class SettingsProbeTest(unittest.TestCase):
    def test_eight_distinct_native_combinations_and_exact_baseline_types(self):
        values=combinations(dict.fromkeys(NAMES,False))
        self.assertEqual(len(values),8)
        self.assertEqual(len({tuple(value[name] for name in NAMES) for value in values}),8)
        for baseline in ({},dict.fromkeys(NAMES,0),dict.fromkeys(NAMES,'false')):
            with self.assertRaises(ValueError):combinations(baseline)

    def test_install_and_remove_only_owned_probe(self):
        with tempfile.TemporaryDirectory() as directory:
            game=Path(directory);mods=game/'bin/x64/plugins/cyber_engine_tweaks/mods';mods.mkdir(parents=True)
            probe=NativeSettingsProbe(game,lambda:False);probe.install()
            self.assertTrue((probe.directory/'init.lua').is_file())
            with self.assertRaises(RuntimeError):probe.install()
            probe.remove_after_exit();self.assertFalse(probe.directory.exists())

    def test_existing_mod_is_never_replaced(self):
        with tempfile.TemporaryDirectory() as directory:
            probe=NativeSettingsProbe(directory,lambda:False);probe.directory.mkdir(parents=True)
            keep=probe.directory/'init.lua';keep.write_text('user source')
            with self.assertRaises(RuntimeError):probe.install()
            self.assertEqual(keep.read_text(),'user source')

    def test_cet_generated_log_and_database_are_removed_after_exit(self):
        with tempfile.TemporaryDirectory() as directory:
            probe=NativeSettingsProbe(directory,lambda:False);probe.directory.parent.mkdir(parents=True);probe.install()
            for name in ('CyberpunkVR_SinglePassRetirementProbe.log','db.sqlite3','db.sqlite3-wal','db.sqlite3-shm'):
                (probe.directory/name).write_bytes(b'generated by owned CET sandbox')
            probe.remove_after_exit();self.assertFalse(probe.directory.exists())

    def test_live_mod_removal_is_refused(self):
        with tempfile.TemporaryDirectory() as directory:
            probe=NativeSettingsProbe(directory,lambda:True)
            with self.assertRaises(RuntimeError):probe.remove_after_exit()

    def test_reporter_file_lock_is_retried_without_recursive_deletion(self):
        probe=NativeSettingsProbe('unused',lambda:False);probe.installed=True
        with patch.object(probe,'_remove_owned_files',side_effect=[PermissionError('reporter lock'),None]) as remove,\
             patch('retirement_settings.time.sleep') as sleep:
            probe.remove_after_exit()
        self.assertEqual(remove.call_count,2);sleep.assert_called_once_with(.1);self.assertFalse(probe.installed)

    def test_unrelated_file_prevents_directory_removal(self):
        with tempfile.TemporaryDirectory() as directory:
            probe=NativeSettingsProbe(directory,lambda:False);probe.directory.parent.mkdir(parents=True);probe.install()
            keep=probe.directory/'user.txt';keep.write_text('keep')
            with self.assertRaises(OSError):probe.remove_after_exit()
            self.assertEqual(keep.read_text(),'keep')

    def test_restore_requires_exact_native_readback(self):
        probe=NativeSettingsProbe('unused',lambda:True);probe.baseline=dict.fromkeys(NAMES,False)
        with patch.object(probe,'command',return_value=dict(values=dict.fromkeys(NAMES,True))):
            with self.assertRaises(RuntimeError):probe.restore_live()
        with patch.object(probe,'command',return_value=dict(values=probe.baseline)):
            self.assertTrue(probe.restore_live());self.assertTrue(probe.restored)

    def test_repeated_cycle_inspects_immutable_baseline_instead_of_recapturing(self):
        probe=NativeSettingsProbe('unused',lambda:True);probe.baseline=dict.fromkeys(NAMES,False)
        status=dict(values=probe.baseline,baseline=probe.baseline,dirty=False)
        with patch.object(probe,'command',return_value=status) as command:
            self.assertEqual(probe.begin(),status);command.assert_called_once_with('inspect')
        for key,value in (('values',dict.fromkeys(NAMES,True)),('baseline',{}),('dirty',True)):
            with patch.object(probe,'command',return_value=dict(status,**{key:value})):
                with self.assertRaises(RuntimeError):probe.begin()

    def test_second_apply_requires_new_restoration(self):
        probe=NativeSettingsProbe('unused',lambda:True);probe.restored=True
        with patch.object(probe,'command',return_value={}) as command:
            probe.apply(dict.fromkeys(NAMES,True));self.assertFalse(probe.restored)
            command.assert_called_once_with('apply',dict.fromkeys(NAMES,True))


@unittest.skipUnless(LuaRuntime,'lupa is required to execute the real retirement probe Lua')
class NativeCVarLuaTest(unittest.TestCase):
    def setUp(self):
        self.lua=LuaRuntime(unpack_returned_tuples=True)
        self.lua.execute('''
events={};files={};writes={};now=100;paused=false;pregame=false;player=true;throwName=nil;ignoreName=nil
actual={['Rendering/DLSSDSeparateParticleColor']=false,['Rendering/DLSSDTransparentGuide']=true,
 ['Developer/FeatureToggles/CharacterSubsurfaceStochastic']=false}
files['settings_probe_run.json']={enabled=true,runId='test',expiresAt=500}
function registerForEvent(name,fn)events[name]=fn end
os.time=function()return now end
io.open=function(path,mode)
 if mode=='r' then
  if not files[path] then return nil end
  return {read=function()return path end,close=function()end}
 end
 return {write=function()end,close=function()end}
end
json={decode=function(path)return files[path] end,encode=function(value)last=value;return 'encoded' end}
Game={GetPlayer=function()return player and {} or nil end,
 GetSystemRequestsHandler=function()return {IsPreGame=function()return pregame end,IsGamePaused=function()return paused end}end}
GameOptions={Get=function(category,name)
 local value=actual[category..'/'..name]
 if type(value)=='boolean' then return tostring(value) end
 return value or ''
end,SetBool=function(category,name,value)
 local key=category..'/'..name
 if throwName==key then error('setter failed') end
 writes[#writes+1]=key
 if ignoreName~=key then actual[key]=value end
end}
''')
        self.lua.execute(Path(__file__).with_name('retirement_settings.lua').read_text())
        self.g=self.lua.globals();self.g.events.onInit()

    def command(self,identifier,action,values=None,run='test'):
        value=dict(runId=run,id=identifier,action=action)
        if values is not None:value['values']=self.lua.table_from(values)
        self.g.files['settings_probe_command.json']=self.lua.table_from(value)
        self.g.events.onUpdate(.2)
        return self.g.last

    def test_capture_apply_restore_actual_native_values(self):
        result=self.command(1,'begin')
        baseline={name:result['values'][name] for name in NAMES}
        self.assertEqual(baseline,dict(zip(NAMES,(False,True,False))))
        self.assertEqual(self.command(2,'apply',dict.fromkeys(NAMES,True)).status,'applied')
        self.assertTrue(all(self.g.actual[name] for name in NAMES))
        result=self.command(3,'restore');self.assertFalse(result.dirty)
        self.assertEqual({name:self.g.actual[name] for name in NAMES},baseline)

    def test_missing_nonboolean_or_unknown_variable_never_sets(self):
        self.command(1,'begin')
        for index,values in enumerate(({},dict.fromkeys(NAMES,0),dict(dict.fromkeys(NAMES,True),other=True)),2):
            self.assertEqual(self.command(index,'apply',values).status,'failed')
        self.assertEqual(len(self.g.writes),0)

    def test_missing_native_option_is_not_false(self):
        self.g.actual[NAMES[0]]=None
        self.assertEqual(self.command(1,'begin').status,'failed')
        self.assertEqual(len(self.g.writes),0)

    def test_native_setter_noop_is_detected_and_rolled_back(self):
        self.command(1,'begin');self.g.ignoreName=NAMES[0]
        result=self.command(2,'apply',dict.fromkeys(NAMES,True))
        self.assertEqual(result.status,'failed');self.assertTrue(result.rollback)
        self.assertFalse(self.g.actual[NAMES[0]]);self.assertTrue(self.g.actual[NAMES[1]]);self.assertFalse(self.g.actual[NAMES[2]])

    def test_mutation_requires_begin(self):
        self.assertEqual(self.command(1,'apply',dict.fromkeys(NAMES,True)).status,'failed')
        self.assertEqual(len(self.g.writes),0)

    def test_stale_foreign_and_replayed_commands_are_ignored(self):
        self.command(1,'begin')
        self.command(2,'apply',dict.fromkeys(NAMES,True),run='foreign')
        self.assertEqual(len(self.g.writes),0)
        self.command(1,'apply',dict.fromkeys(NAMES,True))
        self.assertEqual(len(self.g.writes),0)

    def test_paused_or_pregame_mutation_is_rejected(self):
        self.command(1,'begin');self.g.paused=True
        self.assertEqual(self.command(2,'apply',dict.fromkeys(NAMES,True)).status,'failed')
        self.assertEqual(len(self.g.writes),0)
        self.g.paused=False;self.g.pregame=True
        self.assertEqual(self.command(3,'apply',dict.fromkeys(NAMES,True)).status,'failed')
        self.assertEqual(len(self.g.writes),0)

    def test_expiry_restores_before_disabling(self):
        self.command(1,'begin');self.command(2,'apply',dict.fromkeys(NAMES,True));self.g.now=501
        self.g.events.onUpdate(.2)
        self.assertEqual(self.g.last.status,'expired_restored')
        self.assertFalse(self.g.actual[NAMES[0]]);self.assertTrue(self.g.actual[NAMES[1]]);self.assertFalse(self.g.actual[NAMES[2]])

    def test_shutdown_restores_and_reports_failure_honestly(self):
        self.command(1,'begin');self.command(2,'apply',dict.fromkeys(NAMES,True));self.g.throwName=NAMES[1]
        self.g.events.onShutdown()
        self.assertEqual(self.g.last.status,'shutdown_restore_failed')
        self.assertTrue(self.g.last.dirty)

    def test_one_update_only_applies_one_combination(self):
        self.command(1,'begin');self.command(2,'apply',dict.fromkeys(NAMES,True))
        self.assertEqual(len(self.g.writes),3)
        self.g.events.onUpdate(.2)
        self.assertEqual(len(self.g.writes),3)

    def test_inspection_keeps_original_baseline_across_cycles(self):
        self.command(1,'begin');self.command(2,'apply',dict.fromkeys(NAMES,True));self.command(3,'restore')
        result=self.command(4,'inspect')
        self.assertEqual(result.status,'applied');self.assertFalse(result.dirty)
        self.assertEqual(result['values'][NAMES[0]],False)
        self.assertEqual(result['baseline'][NAMES[1]],True)
        self.assertEqual(len(self.g.writes),6)

    def test_disabled_run_does_not_mutate(self):
        self.g.files['settings_probe_run.json']=None
        lua=LuaRuntime(unpack_returned_tuples=True)
        # The real fixture has no game/setter APIs in a disabled run.
        lua.execute("events={};function registerForEvent(n,f)events[n]=f end;io.open=function()return nil end")
        lua.execute(Path(__file__).with_name('retirement_settings.lua').read_text())
        lua.globals().events.onInit();lua.globals().events.onUpdate(.2);lua.globals().events.onShutdown()


