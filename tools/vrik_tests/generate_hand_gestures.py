"""Bake native closed-finger locals, independently for both hands."""
import gzip,hashlib,json,math,struct
from pathlib import Path
from capture_cyberware_poses import mul,inverse,unit
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'build/cyberware-combat-20261010/combat2'
FIXTURE=ROOT/'tools/vrik_tests/fixtures/gorilla'
names=[s.split('\t')[-1] for s in (FIXTURE/'player_names.txt').read_text().splitlines()]
parents=struct.unpack('<'+'h'*len(names),(FIXTURE/'player_parents.bin').read_bytes())
reference=list(struct.iter_unpack('<12f',(FIXTURE/'reference_full.bin').read_bytes()))
raw=gzip.decompress((SOURCE/'native-attack-poses.bin.gz').read_bytes());stride=12+len(names)*48
samples=[]
for i in range(len(raw)//stride):
    t,phase=struct.unpack_from('<dI',raw,i*stride)
    model=list(struct.iter_unpack('<12f',raw[i*stride+12:(i+1)*stride]))
    if model[23][2]>.5 and model[24][2]>.5:
        local=[unit(mul(inverse(unit(model[parents[b]][4:8])),unit(x[4:8]))) if parents[b]>=0 else unit(x[4:8]) for b,x in enumerate(model)]
        samples.append((t,local))
suffixes=[('InHand'+d,g) for g,d in enumerate(('Thumb','Index','Middle','Ring','Pinky'))]
suffixes += [('Hand'+d+str(j),g) for j in (1,2,3) for g,d in enumerate(('Thumb','Index','Middle','Ring','Pinky')) if not(d=='Thumb' and j==3)]
chosen=[]
for side in ('Left','Right'):
    bend=[names.index(side+'Hand'+d+str(j)) for d in ('Index','Middle','Ring','Pinky') for j in (1,2)]
    def score(sample):return sum(2*math.acos(min(1,abs(sum(a*b for a,b in zip(sample[1][i],reference[i][4:8]))))) for i in bend)
    chosen.append(max(samples,key=score))
def floats(v):
    def one(x):
        t=f'{x:.9g}';return t+('' if '.' in t or 'e' in t else '.0')+'f'
    return '{'+','.join(map(one,v))+'}'
rows=[]
for suffix,group in suffixes:
    close=[];ref=[]
    for side,prefix in enumerate(('Left','Right')):
        idx=names.index(prefix+suffix);close.append(chosen[side][1][idx]);ref.append(list(reference[idx][4:8]))
    rows.append(dict(suffix=suffix,group=group,closed=close,reference=ref))
header=['#pragma once','// Native Gorilla attack finger locals, generated by generate_hand_gestures.py.',
        'namespace cvr::gestures {','struct FingerPose {const char* suffix;int group;float closed[2][4],reference[2][4];};',
        'inline constexpr FingerPose NativeFist[]={']
for r in rows:header.append('    {"'+r['suffix']+'",'+str(r['group'])+',{'+','.join(map(floats,r['closed']))+'},{'+','.join(map(floats,r['reference']))+'}},')
header+=['};','}']
(ROOT/'include/Anim/HandGesturePose.hpp').write_text('\n'.join(header)+'\n')
(ROOT/'tools/vrik_tests/fixtures/hand-gestures.json').write_text(json.dumps(dict(source=str(SOURCE.relative_to(ROOT)),source_sha256=hashlib.sha256((SOURCE/'native-attack-poses.bin.gz').read_bytes()).hexdigest(),native_times=[v[0] for v in chosen],fingers=rows),indent=2))
print('Native fist times', [v[0] for v in chosen],'; finger groups:',len(rows))
