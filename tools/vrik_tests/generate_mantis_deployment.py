"""Generate a mirrored, complete native Mantis suspension in an anatomical frame.

The fixture is the native left-arm deployed sample; the right uses its reflected
bind-space deformation, not another attack phase. +Y is forearm-to-wrist and +Z
is the dorsal (knuckle) side of the hand. No game process is needed.
"""
import math, struct
from pathlib import Path
from capture_cyberware_poses import mul, rotate, inverse, unit, cross, basis

ROOT=Path(__file__).resolve().parents[2]
FIXTURE=Path(__file__).parent/'fixtures/mantis'
names=[line.split('\t',1)[1] for line in (FIXTURE/'player_names.txt').read_text().splitlines()]
parents=struct.unpack('<'+'h'*len(names),(FIXTURE/'player_parents.bin').read_bytes())
def read(name):return [(list(v[:3]),unit(v[4:8])) for v in struct.iter_unpack('<12f',(FIXTURE/name).read_bytes())]
def sub(a,b):return [x-y for x,y in zip(a,b)]
def add(a,b):return [x+y for x,y in zip(a,b)]
def fk(local):
    out=[]
    for i,(p,q) in enumerate(local):
        if parents[i]>=0:
            pp,pq=out[parents[i]];p=add(pp,rotate(pq,p));q=mul(pq,q)
        out.append((p,unit(q)))
    return out
reference=read('reference_full.bin');ref=fk(reference);sample=fk(read('deployed-left.bin'))
def at(model,name):return model[names.index(name)]
def frame(model,side):
    h=('Left','Right')[side];origin,q=at(model,h+'Hand');fore,_=at(model,h+'ForeArm')
    rp,rq=at(ref,h+'Hand')
    normal=unit(cross(sub(at(ref,h+'HandIndex1')[0],rp),sub(at(ref,h+'HandPinky1')[0],rp)))
    normal=[v*(1 if side==0 else -1) for v in normal]
    dorsal=rotate(mul(q,inverse(rq)),normal)
    return origin,basis(unit(sub(origin,fore)),dorsal)
def in_frame(model,i,f):
    origin,q=f;p,r=model[i]
    return rotate(inverse(q),sub(p,origin)),unit(mul(inverse(q),r))
def descendant(i,parent):
    while i>=0:
        if i==parent:return True
        i=parents[i]
    return False
leftRoot=names.index('l_wristSuspension01_JNT');wrist=names.index('l_innerWrist01_JNT')
indices=[i for i,n in enumerate(names) if n.startswith('l_') and descendant(i,leftRoot) and not descendant(i,wrist)]
sampleFrame=frame(sample,0);leftFrame=frame(ref,0);rightFrame=frame(ref,1)
rows=[]
anchors=[]
for side in (0,1):
    for i in indices+[wrist]:
        p,q=in_frame(sample,i,sampleFrame);name=names[i]
        if side:
            name='r_'+name[2:];r=names.index(name)
            lp,lq=in_frame(ref,i,leftFrame);rp,rq=in_frame(ref,r,rightFrame)
            delta=sub(p,lp);delta[0]*=-1;p=add(rp,delta)
            d=unit(mul(q,inverse(lq)));d=[d[0],-d[1],-d[2],d[3]]
            q=unit(mul(d,rq))
        if i==wrist:anchors.append(p)
        else:rows.append((name,p,q))
def floats(values):
    return ','.join((f'{v:.9g}' if '.' in f'{v:.9g}' or 'e' in f'{v:.9g}' else f'{v:.9g}.0')+'f' for v in values)
header=['#pragma once','','// Generated by tools/vrik_tests/generate_mantis_deployment.py.',
    '// Native left deployed suspension, reflected through bind space for the right.',
    '// Frame origin: Hand. +Y: forearm axis. +Z: projected dorsal hand normal.',
    '// Includes suspension, rail, muscles, hinges and skin helpers as one assembly.',
    'namespace cvr::vrik {','struct MantisDeploymentBone { const char* name; float position[3],rotation[4]; };',
    'inline constexpr MantisDeploymentBone MantisDeployment[] = {']
for name,p,q in rows:header.append(f'    {{"{name}",{{{floats(p)}}},{{{floats(q)}}}}},')
lengths=[math.sqrt(sum(x*x for x in reference[names.index(p+'blade02_JNT')][0])) for p in ('l_','r_')]
header+=['};','inline constexpr float MantisDeploymentReferenceLength[2]={'+floats(lengths)+'};','}']
header.insert(-1,'inline constexpr float MantisDeploymentWristAnchor[2][3]={{'+floats(anchors[0])+'},{'+floats(anchors[1])+'}};')
(ROOT/'include/Anim/MantisDeployment.hpp').write_text('\n'.join(header)+'\n')
print(f'Generated {len(rows)} mechanical bones from one native deployed pose')
